/** The nearest area name to a point — the mockup's stand-in for sGeo. */
export function nearestArea(lat, lng) {
  let best = null;
  let bestD = Infinity;
  for (const [name, [a, b]] of Object.entries(AREAS)) {
    const d = (a - lat) ** 2 + (b - lng) ** 2;
    if (d < bestD) {
      bestD = d;
      best = name;
    }
  }
  return best;
}
